#' visualbrief: from campaign data to clear, reusable reports
#'
#' visualbrief takes the results of a digital campaign (exports from
#' advertising platforms, social media tools, web analytics or a spreadsheet)
#' and turns them into summaries, comparisons with confidence intervals,
#' branded charts and a self-contained report. It answers practical questions
#' (which content works with which audience, how results change over time, how
#' to present them to a client or team) while stating what campaign data can
#' and cannot show.
#'
#' A typical workflow:
#' 1. [vb_campaign()] or [vb_read_csv()] to standardise the data;
#' 2. [vb_summarise()], [vb_compare()] and [vb_trend()] to analyse it;
#' 3. [vb_brand()] or [vb_brand_yml()] and [vb_check_contrast()] for an
#'    accessible visual identity;
#' 4. [vb_plot_rates()], [vb_plot_trend()] and [vb_report()] to communicate.
#'
#' See `vignette("visualbrief")`.
#'
